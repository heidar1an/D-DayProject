/* ─────────────────────── بلوک مرجع → متن غنی ───────────────────────
 *
 * خروجی فقط تگ‌های مجازِ پاک‌ساز (`database/sanitizeHtml.js`) دارد و کلاس‌های
 * کادرها همان کلاس‌های میکرودرسنامه است (`micr-callout--key/def/warn/clinical`)
 * تا پیش‌نمایش ویرایشگر پنل و خوانندهٔ آیندهٔ رفرنس‌ها یک ظاهر بگیرند.
 * بلوک `image` از تبدیل کنار گذاشته می‌شود: متن نیست و تصویر مرجع را ادمین
 * با کتابخانهٔ رسانه در جای خودش می‌گذارد (همان الگوی بلوک‌های تعاملی میکرو).
 */

const CALLOUT_CLASS = {
  definition: 'def',
  exam: 'key',
  important: 'key',
  keypoint: 'key',
  warning: 'warn',
  clinical: 'clinical',
};

const CALLOUT_LABEL = {
  definition: 'تعریف',
  exam: 'نقطهٔ امتحانی',
  important: 'نکتهٔ مهم',
  keypoint: 'نکتهٔ کلیدی',
  warning: 'هشدار / اشتباه رایج',
  clinical: 'ارتباط بالینی',
};

const escapeHtml = (value) => String(value ?? '')
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const calloutHtml = (variant, title, text) => {
  const className = CALLOUT_CLASS[variant] ?? 'key';
  const label = CALLOUT_LABEL[variant] ?? 'نکته';
  const heading = title && title !== label
    ? `<p><span class="micr-callout__tag">${escapeHtml(label)}</span> <strong>${escapeHtml(title)}</strong></p>`
    : `<p><strong>${escapeHtml(label)}</strong></p>`;

  return `<div class="micr-callout micr-callout--${className}">${heading}<p>${escapeHtml(text)}</p></div>`;
};

const tableHtml = (block) => {
  const headers = (Array.isArray(block.headers) ? block.headers : []).filter(Boolean);
  const rows = (Array.isArray(block.rows) ? block.rows : []).filter((row) => Array.isArray(row) && row.length);
  if (!headers.length && !rows.length) return '';

  const thead = headers.length
    ? `<thead><tr>${headers.map((cell) => `<th>${escapeHtml(cell)}</th>`).join('')}</tr></thead>`
    : '';
  const tbody = `<tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`).join('')}</tbody>`;
  const caption = block.caption ? `<p class="micr-block__label">${escapeHtml(block.caption)}</p>` : '';

  return `<div class="micr-table">${caption}<div class="micr-table__scroll"><table>${thead}${tbody}</table></div></div>`;
};

export function referenceBlockToHtml(block) {
  switch (block?.type) {
    case 'p':
      return block.text ? `<p>${escapeHtml(block.text)}</p>` : '';

    case 'quote':
      if (!block.text) return '';
      return `<blockquote><p>${escapeHtml(block.text)}</p>${block.cite ? `<p>— ${escapeHtml(block.cite)}</p>` : ''}</blockquote>`;

    case 'callout':
      return block.text ? calloutHtml(block.variant, block.title, block.text) : '';

    case 'table':
      return tableHtml(block);

    case 'formula':
      if (!block.expr) return '';
      return `<p><code>${escapeHtml(block.expr)}</code>${block.note ? ` — ${escapeHtml(block.note)}` : ''}</p>`;

    case 'divider':
      return '<hr>';

    /* image → متن نیست؛ تصویر را ادمین از کتابخانهٔ رسانه درج می‌کند */
    default:
      return '';
  }
}

/* تبدیل بلوک‌های یک مبحث به متن غنی — برای seed پنل */
export function referenceBlocksToHtml(blocks) {
  return (Array.isArray(blocks) ? blocks : [])
    .map(referenceBlockToHtml)
    .filter(Boolean)
    .join('\n');
}
